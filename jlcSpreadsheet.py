# @brief Filters out rows for specific labels of BOMS and CPL csv's generated by the Eagle JLCPCB ULP
# @param spreadsheet_file Path to the spreadsheet
# @return nothing
def ulp_csv_update(spreadsheet_file):
    updated_csv_output = (
        str(spreadsheet_file.parent.parent) + "/manufacturing/" + spreadsheet_file.name
    )

    # Split by path designators and keep the last split which is the file itself.
    print(f"\nReading from {spreadsheet_file}\n")
    # Read in the given cs, can be position or BOM csv.
    csv_pd = pd.read_csv(spreadsheet_file)
    # Return a copy of the csv that removes the rows from the column "Designator" that match the labels within
    # "exclude_labels". Note that this is in fact making a csv that match the labels of the list, but inverts the
    # matching behavior: ~
    updated_csv = csv_pd[~csv_pd["Designator"].str.contains("|".join(exclude_labels))]
    alphabetized_csv = updated_csv.sort_values("Designator")

    # Print it so that we can check it at a glance on the terminal
    print(alphabetized_csv)

    print("Placed here: {0}".format(updated_csv_output))
    alphabetized_csv.to_csv(updated_csv_output, index=False)

    if spreadsheet_file.stem == "bom":
        print("Updating bom file")
        add_jlc_part_numbers_to_csv(spreadsheet_file.parent.parent, updated_csv_output)
    else:
        print("Skipping this csv.")


def add_jlc_part_numbers_to_csv(csv_directory, updated_csv_file):
    pg_admin_file = None
    csv_directory_parent = csv_directory.parent
    for file in csv_directory_parent.iterdir():
        if "data" in file.stem:
            pg_admin_file = file

    if pg_admin_file is None:
        print("Could not find data file in {0}".format(csv_directory_parent))
        return

    csv_with_part_number = pd.read_csv(pg_admin_file)
    csv_without_part_numbers = pd.read_csv(updated_csv_file)

    if (
        "Value" not in csv_without_part_numbers.columns
        or "Quantity" not in csv_without_part_numbers.columns
    ):
        return

    csv_without_part_numbers["LCSC Part #"] = csv_without_part_numbers.apply(
        lambda row: m.iloc[0]["suppliers_part_number"]
        if len(
            m := csv_with_part_number[
                csv_with_part_number["component_name"].str.contains(
                    str(row["Value"]), regex=False
                )
                & (
                    csv_with_part_number["component_qty"].astype(int)
                    == int(row["Quantity"])
                )
            ]
        )
        == 1
        else None,
        axis=1,
    )

    csv_without_part_numbers.to_csv(updated_csv_file, index=False)


def cam_board_eagle(board_file, layers=2):
    output_dir = str(board_file.parent.parent) + "/manufacturing/"

    if layers == 2:
        subprocess.run(
            [
                "eagle",
                "-X",
                "-dCAMJOB",
                f"-j{CAM_FILE_TWO_LAYER}",
                f"-o{output_dir}",
                str(board_file),
            ]
        )
    elif layers == 4:
        subprocess.run(
            [
                "eagle",
                "-X",
                "-dCAMJOB",
                f"-j{CAM_FILE_FOUR_LAYER}",
                f"-o{output_dir}",
                str(board_file),
            ]
        )
    else:
        print("Pick number of layers...")


def cam_board_kicad(board_file):
    output_dir = str(board_file.parent.parent) + "/manufacturing/"

    subprocess.run(
        [
            "flatpak",
            "run",
            "--command=kicad-cli",
            "org.kicad.KiCad",
            "pcb",
            "export",
            "gerbers",
            "--output",
            output_dir,
            "--layers",
            "F.Cu,In1.Cu,In2.Cu,In3.Cu,In4.Cu,B.Cu,F.Paste,B.Paste,F.Silkscreen,B.Silkscreen,F.Mask,B.Mask,Edge.Cuts",
            str(board_file),
        ]
    )

    subprocess.run(
        [
            "flatpak",
            "run",
            "--command=kicad-cli",
            "org.kicad.KiCad",
            "pcb",
            "export",
            "drill",
            "--output",
            output_dir,
            str(board_file),
        ]
    )


def run_fabricate_plugin(board_file):
    result = subprocess.run(
        [
            "flatpak",
            "run",
            "--command=bash",
            "org.kicad.KiCad",
            "-c",
            f"cd {PATH_FAB_PLUGIN} && python3 -m {FABRICATION_TOOLKIT_MODULE}.cli -p {str(board_file)}",
        ]
    )

    return result.returncode


