# @brief Filters out rows for specific labels of BOMS and CPL csv's generated by the Eagle JLCPCB ULP
# @param spreadsheet_file Path to the spreadsheet
# @return nothing
def ulp_csv_update(spreadsheet_file):
    updated_csv_output = (
        str(spreadsheet_file.parent.parent) + "/Manufacturing/" + spreadsheet_file.name
    )

    # Split by path designators and keep the last split which is the file itself.
    print(f"\nReading from {spreadsheet_file}\n")
    # Read in the given cs, can be position or BOM csv.
    csv_pd = pd.read_csv(spreadsheet_file)
    # Return a copy of the csv that removes the rows from the column "Designator" that match the labels within
    # "designator_exclude_labels". Note that this is in fact making a csv that match the labels of the list, but inverts the
    # matching behavior: ~
    updated_csv = csv_pd[
        ~csv_pd["Designator"].str.contains("|".join(designator_exclude_labels))
    ]

    if spreadsheet_file.stem != "positions":
        updated_csv = updated_csv[
            ~updated_csv["Footprint"].str.contains("|".join(footprint_exclude_labels))
        ]

    alphabetized_csv = updated_csv.sort_values("Designator")

    # Print it so that we can check it at a glance on the terminal
    print(alphabetized_csv)

    print("Update CSV is here: {0}\n".format(updated_csv_output))
    alphabetized_csv.to_csv(updated_csv_output, index=False)

    if spreadsheet_file.stem == "bom":
        print("Merging BOM and JLCPCB Part Numbers")
        add_jlc_part_numbers_to_csv(spreadsheet_file.parent.parent, updated_csv_output)
    else:
        print("Skipping non-BOM CSV.")


def add_jlc_part_numbers_to_csv(csv_directory, updated_csv_file):
    pg_admin_file = None
    csv_directory_parent = csv_directory.parent
    for file in csv_directory_parent.iterdir():
        if "data" in file.stem:
            pg_admin_file = file
            break

    if pg_admin_file is None:
        print(
            "\n-------\nSkipping\nCould not find data file in {0}\n--------\n".format(
                csv_directory_parent
            )
        )
        return

    print("Found Data File")

    csv_with_part_number = pd.read_csv(pg_admin_file)
    csv_without_part_numbers = pd.read_csv(updated_csv_file)

    if (
        "Value" not in csv_without_part_numbers.columns
        or "Quantity" not in csv_without_part_numbers.columns
    ):
        print("\nCould not find columns of interest in CSV.\n")
        return

    csv_without_part_numbers["LCSC Part #"] = csv_without_part_numbers.apply(
        lambda row: m.iloc[0]["suppliers_part_number"]
        if len(
            m := csv_with_part_number[
                csv_with_part_number["component_name"].str.contains(
                    str(row["Value"]), regex=False, case=False
                )
                & (
                    csv_with_part_number["component_qty"].astype(int)
                    == int(row["Quantity"])
                )
            ]
        )
        == 1
        else None,
        axis=1,
    )

    print("Done merging files.")
    print("Manually adding certain LCSC Part numbers.")
    csv_without_part_numbers.loc[
        csv_without_part_numbers["Value"].str.contains(
            "QWIIC_RA|1X04_1MM_RA|Qwiic_Right_Angle", case=False
        ),
        "LCSC Part #",
    ] = "C2859067"
    csv_without_part_numbers.loc[
        csv_without_part_numbers["Value"].str.contains(
            "QWIIC_Vertical|Vertical Qwiic Connector", case=False
        ),
        "LCSC Part #",
    ] = "C9900142565"
    csv_without_part_numbers.loc[
        csv_without_part_numbers["Value"].str.contains(
            "USB_C_Receptacle|USB Female Type C Connector", case=False
        ),
        "LCSC Part #",
    ] = "C709357 or C393939 or C165948"
    csv_without_part_numbers.loc[
        csv_without_part_numbers["Value"].str.contains(
            "TACTILE_SWITCH_SMD_4.6X2.8MM|MOMENTARY-SWITCH-SPST-SMD-4.6X2.8MM|Reset|Boot",
            case=False,
        ),
        "LCSC Part #",
    ] = "C2888425 or C2690011 or C920226"

    csv_without_part_numbers.to_csv(updated_csv_file, index=False)


def parse_eagle_brd(board_file):
    root = ET.parse(board_file).getroot()
    board = root.find("drawing/board")

    # Build set of (library, package) combos that have at least one SMD pad or TH pad.
    # This mirrors the ULP's contact check: only elements whose package has real contacts
    # are included (filters out logos, silkscreen labels, buzzard labels, etc.).
    # All was taken from jlpcb exporting ulp written for Eagle.
    assert board is not None
    smt_packages = set()
    # All the vital information hre
    for lib in board.findall("libraries/library"):
        lib_name = lib.get("name")
        for pkg in lib.findall(".//package"):
            if pkg.find("smd") is not None or pkg.find("pad") is not None:
                smt_packages.add((lib_name, pkg.get("name")))

    rows = []
    for el in board.findall("elements/element"):
        # skip DNP
        if el.get("populate") == "no":
            continue

        lib, pkg = el.get("library"), el.get("package")
        if (lib, pkg) not in smt_packages:
            continue

        child_attrs = {
            a.get("name"): a.get("value", "") for a in el.findall("attribute")
        }

        if "DNP" in child_attrs:
            continue

        rot = el.get("rot", "R0")
        mirrored = rot.startswith("M")
        angle = float(rot.lstrip("MR") or "0")
        if "JLC_ROTATION" in child_attrs:
            angle = (angle + float(child_attrs["JLC_ROTATION"])) % 360

        rows.append(
            {
                "Designator": el.get("name"),
                "Value": el.get("value", ""),
                "Footprint": pkg,
                "Mid X": float(el.get("x")),
                "Mid Y": float(el.get("y")),
                "Layer": "Bottom" if mirrored else "Top",
                "Rotation": angle % 360,
                "LCSC Part #": child_attrs.get("LCSC_PART")
                or child_attrs.get("LCSC", ""),
            }
        )

    return pd.DataFrame(rows)


def eagle_brd_to_manufacturing_csvs(board_file):
    production_directory = str(board_file.parent) + "/production/"
    Path(production_directory).mkdir(exist_ok=True)

    df = parse_eagle_brd(board_file)

    # CPL
    cpl = df[["Designator", "Mid X", "Mid Y", "Layer", "Rotation"]].sort_values(
        "Designator"
    )
    cpl_path = production_directory + "positions.csv"
    cpl.to_csv(cpl_path, index=False)
    print(f"Position file written here: {cpl_path}")

    # BOM — empty-value components get individual rows; others are grouped by value+footprint
    bom_rows = []
    df_sorted = df.sort_values(["Value", "Footprint", "Designator"])

    for _, row in df_sorted[df_sorted["Value"].str.strip() == ""].iterrows():
        bom_rows.append(
            {
                "Designator": row["Designator"],
                "Footprint": row["Footprint"],
                "Quantity": 1,
                "Value": "",
                "LCSC Part #": row["LCSC Part #"],
            }
        )

    has_value = df_sorted[df_sorted["Value"].str.strip() != ""]
    for (value, footprint), group in has_value.groupby(
        ["Value", "Footprint"], sort=True
    ):
        bom_rows.append(
            {
                "Designator": " ".join(group["Designator"].tolist()),
                "Footprint": footprint,
                "Quantity": len(group),
                "Value": value,
                "LCSC Part #": group["LCSC Part #"].iloc[0],
            }
        )

    bom = pd.DataFrame(
        bom_rows,
        columns=["Designator", "Footprint", "Quantity", "Value", "LCSC Part #"],
    )
    bom_path = production_directory + "bom.csv"
    bom.to_csv(bom_path, index=False)
    print(f"BOM file written here: {bom_path}")
    return 0


def cam_board_eagle(board_file, layers=2):
    output_dir = str(board_file.parent) + "/Manufacturing/"

    if layers == 2:
        subprocess.run(
            [
                "eagle",
                "-X",
                "-dCAMJOB",
                f"-j{CAM_FILE_TWO_LAYER}",
                f"-o{output_dir}",
                str(board_file),
            ]
        )
    elif layers == 4:
        subprocess.run(
            [
                "eagle",
                "-X",
                "-dCAMJOB",
                f"-j{CAM_FILE_FOUR_LAYER}",
                f"-o{output_dir}",
                str(board_file),
            ]
        )
    else:
        print("Pick number of layers...")


# @brief Calls the built in CAMMER from
def cam_board_kicad(board_file):
    output_dir = str(board_file.parent) + "/Manufacturing/"

    subprocess.run(
        [
            "flatpak",
            "run",
            "--command=kicad-cli",
            "org.kicad.KiCad",
            "pcb",
            "export",
            "gerbers",
            "--output",
            output_dir,
            "--layers",
            "F.Cu,In1.Cu,In2.Cu,In3.Cu,In4.Cu,B.Cu,F.Paste,B.Paste,F.Silkscreen,B.Silkscreen,F.Mask,B.Mask,Edge.Cuts",
            str(board_file),
        ]
    )

    subprocess.run(
        [
            "flatpak",
            "run",
            "--command=kicad-cli",
            "org.kicad.KiCad",
            "pcb",
            "export",
            "drill",
            "--output",
            output_dir,
            str(board_file),
        ]
    )


def run_fabricate_plugin_kicad(board_file):
    result = subprocess.run(
        [
            "flatpak",
            "run",
            "--command=bash",
            "org.kicad.KiCad",
            "-c",
            f"cd {PATH_FAB_PLUGIN} && python3 -m {FABRICATION_TOOLKIT_MODULE}.cli -p {str(board_file)}",
        ]
    )

    return result.returncode


